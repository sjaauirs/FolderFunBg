param(
    [switch]$SkipTests
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$artifacts = Join-Path $root "artifacts"
$stage = Join-Path $artifacts "payload"
$publishDir = Join-Path $artifacts "settings"
$payloadZip = Join-Path $artifacts "payload.zip"
$setupOut = Join-Path $artifacts "setup"

Push-Location $root
try {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (-not (Test-Path $vswhere)) {
        throw "vswhere.exe not found. Install Visual Studio 2022 with the C++ desktop workload."
    }

    $vsPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if (-not $vsPath) {
        throw "Visual Studio with the C++ desktop workload was not found."
    }

    $vcvars = Join-Path $vsPath "VC\Auxiliary\Build\vcvarsall.bat"
    $msbuild = Join-Path $vsPath "MSBuild\Current\Bin\MSBuild.exe"
    $nativeProject = Join-Path $root "src\FolderFunBg.Hook\FolderFunBg.Hook.vcxproj"
    $env:PATH = (Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer") + ";" + $env:PATH

    Write-Host "1/6 Building native hook (Release|x64)..."
    & cmd.exe /c "call `"$vcvars`" x64 >nul && `"$msbuild`" `"$nativeProject`" /p:Configuration=Release /p:Platform=x64 /m /nologo /v:minimal"
    if ($LASTEXITCODE -ne 0) {
        throw "Native build failed."
    }

    Write-Host "2/6 Publishing the settings app (self-contained)..."
    if (Test-Path $publishDir) {
        Remove-Item $publishDir -Recurse -Force
    }
    dotnet publish (Join-Path $root "src\FolderFunBg.Settings\FolderFunBg.Settings.csproj") `
        -c Release -r win-x64 --self-contained true `
        -p:WindowsAppSDKSelfContained=true -p:PublishSingleFile=false `
        -p:DebugType=None -p:DebugSymbols=false `
        -o $publishDir --nologo
    if ($LASTEXITCODE -ne 0) {
        throw "Settings app publish failed."
    }

    # WinUI's self-contained publish currently omits the app's merged PRI file.
    # Without it the installed app crashes at XAML startup (0xC000027B), so
    # copy the PRI generated by the build next to the published executable.
    $appPri = Get-ChildItem (Join-Path $root "src\FolderFunBg.Settings\bin") `
        -Recurse -Filter "FolderFunBg.Settings.pri" -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (-not $appPri) {
        throw "FolderFunBg.Settings.pri was not found; the published app would not start."
    }
    Copy-Item $appPri.FullName (Join-Path $publishDir "FolderFunBg.Settings.pri") -Force
    Write-Host "    copied app PRI: $($appPri.FullName)"

    if (-not $SkipTests) {
        Write-Host "3/6 Running core tests..."
        dotnet test (Join-Path $root "tests\FolderFunBg.Core.Tests\FolderFunBg.Core.Tests.csproj") `
            -c Release --nologo
        if ($LASTEXITCODE -ne 0) {
            throw "Core tests failed."
        }
    }
    else {
        Write-Host "3/6 Skipping tests."
    }

    Write-Host "4/6 Staging payload..."
    if (Test-Path $stage) {
        Remove-Item $stage -Recurse -Force
    }
    New-Item -ItemType Directory -Force -Path (Join-Path $stage "Hook") | Out-Null
    Copy-Item (Join-Path $root "bin\x64\Release\FolderFunBg.Hook.dll") (Join-Path $stage "Hook") -Force
    Copy-Item $publishDir (Join-Path $stage "Settings") -Recurse -Force
    Copy-Item (Join-Path $root "LICENSE") $stage -Force
    Copy-Item (Join-Path $root "NOTICE.md") $stage -Force

    # Symbols are not needed inside the installed app and roughly double its size.
    Get-ChildItem $stage -Recurse -Filter *.pdb -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue

    if (Test-Path $payloadZip) {
        Remove-Item $payloadZip -Force
    }
    Compress-Archive -Path (Join-Path $stage "*") -DestinationPath $payloadZip -CompressionLevel Optimal
    $payloadSize = [Math]::Round((Get-Item $payloadZip).Length / 1MB, 1)
    Write-Host "    payload.zip: $payloadSize MB"

    Write-Host "5/6 Building the installer EXE..."
    if (Test-Path $setupOut) {
        Remove-Item $setupOut -Recurse -Force
    }
    dotnet publish (Join-Path $root "installer\FolderFunBg.Installer\FolderFunBg.Installer.csproj") `
        -c Release -r win-x64 --self-contained true `
        -p:PublishSingleFile=true -p:PayloadZip="$payloadZip" `
        -p:DebugType=None -p:DebugSymbols=false `
        -o $setupOut --nologo
    if ($LASTEXITCODE -ne 0) {
        throw "Installer build failed."
    }

    Write-Host "6/6 Staging the installer..."
    New-Item -ItemType Directory -Force -Path (Join-Path $root "install") | Out-Null
    $setupExe = Join-Path $setupOut "FolderFunBg-Setup.exe"
    Copy-Item $setupExe (Join-Path $root "install\FolderFunBg-Setup.exe") -Force
    $hash = (Get-FileHash (Join-Path $root "install\FolderFunBg-Setup.exe") -Algorithm SHA256).Hash
    Set-Content (Join-Path $root "install\FolderFunBg-Setup.exe.sha256") "$hash  FolderFunBg-Setup.exe"

    $setupSize = [Math]::Round((Get-Item (Join-Path $root "install\FolderFunBg-Setup.exe")).Length / 1MB, 1)
    Write-Host ""
    Write-Host "Installer built."
    Write-Host "  EXE   : install\FolderFunBg-Setup.exe ($setupSize MB)"
    Write-Host "  SHA256: $hash"
}
finally {
    Pop-Location
}
